
# Creating a tuple
t = (10, 20, 30, 40, 50)

# Printing tuple
print("Tuple:", t)

# Accessing elements
print("First element:", t[0])
print("Last element:", t[-1])

# Finding length
print("Length:", len(t))

# Slicing
print("Slicing:", t[1:4])

# Counting elements
print("Count:", t.count(10))

# Finding index
print("Index:", t.index(30))

# Using for loop
print("Tuple elements:")
for i in t:
    print(i)
